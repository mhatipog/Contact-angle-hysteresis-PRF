"""Stationary microscopic wetting folds in an exact cantilever reduction.

Independent, quasi-static continuation of the Bradley--Hewitt--Vella beam
energy. The Green kernel is exact for a clamped/free Euler--Bernoulli beam;
this is NOT the full lubrication PDE, a microscopic force law or a proof of
rate-independent hysteresis in an experiment.

Each Young multiplier is generated by ONE smooth surface-energy field; no
independent advancing/receding angle interval is prescribed.
"""
from dataclasses import dataclass
import math
import numpy as np
from scipy.optimize import root


@dataclass(frozen=True)
class Pattern:
    nu: float = 4.0
    cosine_reference: float = .9
    mean_multiplier: float = 1.0
    amplitude: float = .1
    wavelength: float = .075
    phase: float = 0.0

    def __post_init__(self):
        if self.wavelength <= 0 or self.nu <= 0:
            raise ValueError("Need positive wavelength and elasto-capillary number")
        if self.cosine_reference <= 0 or self.cosine_reference * (
                self.mean_multiplier + abs(self.amplitude)) > 1:
            raise ValueError("Young cosine is outside its physical range")
        if self.cosine_reference * (self.mean_multiplier - abs(self.amplitude)) <= 0:
            raise ValueError("Young cosine must remain positive in this model")

    @property
    def wave_number(self):
        return 2 * math.pi / self.wavelength

    def multiplier(self, x):
        return self.mean_multiplier + self.amplitude * np.sin(self.wave_number*x+self.phase)

    def derivative(self, x):
        return self.amplitude * self.wave_number * np.cos(self.wave_number*x+self.phase)

    def integral(self, a, b):
        k = self.wave_number
        return (self.mean_multiplier*(b-a) + self.amplitude/k*(
            np.cos(k*a+self.phase)-np.cos(k*b+self.phase)))


def beam_compliance(a, b):
    """I=integral_a^b integral_a^b G(x,s) ds dx; EI is scaled to unity."""
    d = b-a
    q = (a+b)/2
    I = d**5/120 + d*d*q**3/3
    Id = d**4/24 + 2*d*q**3/3
    Iq = d*d*q*q
    Idd = d**3/6 + 2*q**3/3
    Idq = 2*d*q*q
    Iqq = 2*d*d*q
    Ia, Ib = -Id + Iq/2, Id + Iq/2
    Iaa = Idd - Idq + Iqq/4
    Iab = -Idd + Iqq/4
    Ibb = Idd + Idq + Iqq/4
    return I, np.array([Ia,Ib]), np.array([[Iaa,Iab],[Iab,Ibb]])


def state(a, b, volume, pattern=Pattern(), check_physical=True):
    """Energy, gradient, Hessian and volume-conjugate pressure (non-dimensional)."""
    if not (0 < a < b < 1 and 0 < volume < b-a):
        raise ValueError("Require 0<a<b<1 and 0<V<b-a (suction branch)")
    I, dI, ddI = beam_compliance(a, b)
    R = volume-(b-a)
    pressure = R/I
    # Beam height decreases monotonically towards the free end for p<0.
    K_tip = (b**3-a**3)/6-(b**4-a**4)/24
    if check_physical and 1+pressure*K_tip <= 0:
        raise ValueError("Elastic walls touch or cross at the free end")
    dR = np.array([1.0,-1.0])
    gy = np.array([pattern.multiplier(a),-pattern.multiplier(b)])*pattern.nu
    hy = np.diag([pattern.derivative(a),-pattern.derivative(b)])*pattern.nu
    energy = R*R/(2*I) - pattern.nu*pattern.integral(a,b)
    gradient = R*dR/I - .5*pressure**2*dI + gy
    hessian = (np.outer(dR,dR)/I
               - R*(np.outer(dR,dI)+np.outer(dI,dR))/I**2
               + R*R*np.outer(dI,dI)/I**3
               - R*R*ddI/(2*I**2) + hy)
    return energy, gradient, hessian, pressure


def fold_residual(z, pattern=Pattern()):
    a,b,volume = z
    try:
        _,grad,H,_ = state(a,b,volume,pattern)
    except ValueError:
        return np.array([1e2,1e2,1e2])
    # det(H)=0 identifies a zero eigenvalue; dimensionless scale conditions root.
    return np.array([grad[0],grad[1],np.linalg.det(H)/100])


def find_fold(seed, pattern=Pattern()):
    solution = root(fold_residual, seed, args=(pattern,), tol=1e-11)
    if not solution.success and np.linalg.norm(solution.fun)>1e-8:
        raise RuntimeError(f"No converged fold: {solution.message}")
    a,b,volume = solution.x
    residual = fold_residual(solution.x,pattern)
    _,grad,H,p = state(a,b,volume,pattern)
    eigenvalues, modes = np.linalg.eigh(H)
    if np.linalg.norm(residual)>1e-7 or eigenvalues[1] <= 0 or abs(eigenvalues[0])>1e-5:
        raise RuntimeError("Root is not a simple loss-of-stability fold")
    return dict(a=float(a),b=float(b),volume=float(volume),pressure=float(p),
                eigenvalues=eigenvalues,soft_mode=modes[:,0],residual=residual)


def effective_left_curvature(H):
    """Relax the right meniscus at fixed left coordinate: exact 2x2 Schur complement."""
    if H[1,1] <= 0:
        raise ValueError("Right line must be locally stable before elimination")
    return float(H[0,0]-H[0,1]**2/H[1,1])


def gradient_flow_energy_balance(a,b,volume,pattern=Pattern(),mobility=(1.,1.),volume_rate=0.):
    """Instantaneous identity for illustrative diagonal overdamped mobility.

    This is an identity of the reduced toy kinetics, not a claimed full
    fluid/beam dissipation law for the original lubrication equations.
    """
    _,g,_,pressure=state(a,b,volume,pattern)
    M=np.asarray(mobility,float)
    if M.shape != (2,) or np.any(M<=0):
        raise ValueError("Both mobilities must be positive")
    velocity=-M*g
    dissipation=float(np.dot(M*g,g))
    power=float(np.dot(g,velocity)+pressure*volume_rate)
    return velocity,power,dissipation,float(pressure*volume_rate)


